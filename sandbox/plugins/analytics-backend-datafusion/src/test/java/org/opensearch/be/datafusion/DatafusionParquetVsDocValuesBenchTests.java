    private static long median(long[] values) {
        long[] sorted = values.clone();
        Arrays.sort(sorted);
        return sorted[sorted.length / 2];
    }

    private long asyncCall(Consumer<ActionListener<Long>> call) {
        CompletableFuture<Long> future = new CompletableFuture<>();
        call.accept(new ActionListener<>() {
            @Override
            public void onResponse(Long v) {
                future.complete(v);
            }

            @Override
            public void onFailure(Exception e) {
                future.completeExceptionally(e);
            }
        });
        return future.join();
    }

    /** Applies the consumer to each drained batch, then closes it. */
    private static final class ConsumingSink implements ExchangeSink {
        private final Consumer<VectorSchemaRoot> perBatch;

        ConsumingSink(Consumer<VectorSchemaRoot> perBatch) {
            this.perBatch = perBatch;
        }

        @Override
        public synchronized void feed(VectorSchemaRoot batch) {
            try {
                perBatch.accept(batch);
            } finally {
                batch.close();
            }
        }

        @Override
        public void close() {}
    }

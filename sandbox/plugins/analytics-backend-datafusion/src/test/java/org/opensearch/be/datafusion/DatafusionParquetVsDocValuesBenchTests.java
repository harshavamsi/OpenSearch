    /**
     * Full path D run: decode the query's columns per 4096-doc batch straight into Arrow
     * vectors and feed them into a {@link DatafusionReduceSink} (LocalSession partition
     * stream) executing the equivalent GROUP BY; drain into {@code perBatch}.
     */
    private void runDocValues(
        DirectoryReader reader,
        NativeRuntimeHandle runtimeHandle,
        RootAllocator alloc,
        QuerySpec q,
        Consumer<VectorSchemaRoot> perBatch
    ) throws Exception {
        ConsumingSink downstream = new ConsumingSink(perBatch);
        ExchangeSinkContext ctx = new ExchangeSinkContext(
            "pvd-" + q.name() + "-" + System.nanoTime(),
            0,
            0L,
            buildAggSubstrait(q),
            alloc,
            List.of(new ExchangeSinkContext.ChildInput(0, buildPassthroughSubstrait(q))),
            downstream
        );
        DatafusionReduceSink sink = new DatafusionReduceSink(ctx, runtimeHandle);
        try {
            PlainActionFuture<Void> done = PlainActionFuture.newFuture();
            AtomicReference<Throwable> drainFailure = new AtomicReference<>();
            Thread drainer = new Thread(() -> {
                try {
                    sink.reduce(done);
                } catch (Throwable t) {
                    drainFailure.set(t);
                }
            }, "pvd-drainer");
            drainer.start();

            ExchangeSink child = sink.sinkForChild(0);
            LeafReader leaf = reader.leaves().get(0).reader();
            int cols = q.dvColumns().length;
            NumericDocValues[] dvs = new NumericDocValues[cols];
            for (int c = 0; c < cols; c++) {
                dvs[c] = leaf.getNumericDocValues(q.dvColumns()[c]);
                assertNotNull(q.dvColumns()[c], dvs[c]);
            }
            Schema schema = batchSchema(q);
            int[] docs = new int[BATCH];
            int maxDoc = leaf.maxDoc();
            for (int start = 0; start < maxDoc; start += BATCH) {
                int len = Math.min(BATCH, maxDoc - start);
                for (int i = 0; i < len; i++) {
                    docs[i] = start + i;
                }
                VectorSchemaRoot root = VectorSchemaRoot.create(schema, alloc);
                for (int c = 0; c < cols; c++) {
                    BigIntVector vec = (BigIntVector) root.getVector(c);
                    vec.allocateNew(len);
                    long byteLen = (long) len * Long.BYTES;
                    MemorySegment dst = MemorySegment.ofAddress(vec.getDataBuffer().memoryAddress()).reinterpret(byteLen);
                    if (dvs[c].longValuesInto(len, docs, 0, dst, 0L, 0L)) {
                        directBatches++;
                    } else {
                        // Correctness fallback: heap decode + bulk copy (still no per-value set loop).
                        fallbackBatches++;
                        dvs[c].longValues(len, docs, 0, fallbackScratch, 0, 0L);
                        dst.copyFrom(MemorySegment.ofArray(fallbackScratch).asSlice(0, byteLen));
                    }
                    vec.getValidityBuffer().setOne(0, (len + 7) / 8);
                    vec.setValueCount(len);
                }
                root.setRowCount(len);
                child.feed(root);
            }
            child.close();
            done.actionGet(300, TimeUnit.SECONDS);
            drainer.join(TimeUnit.SECONDS.toMillis(30));
            if (drainFailure.get() != null) {
                throw new IllegalStateException("drain failed", drainFailure.get());
            }
        } finally {
            sink.close();
        }
    }

    /** Decode-only cost: same batch loop, no DataFusion — isolates the doc_values→Arrow stage. */
    private long timeDecodeOnly(DirectoryReader reader, RootAllocator alloc, QuerySpec q) throws Exception {
        LeafReader leaf = reader.leaves().get(0).reader();
        int cols = q.dvColumns().length;
        NumericDocValues[] dvs = new NumericDocValues[cols];
        for (int c = 0; c < cols; c++) {
            dvs[c] = leaf.getNumericDocValues(q.dvColumns()[c]);
        }
        int[] docs = new int[BATCH];
        int maxDoc = leaf.maxDoc();
        long t0 = System.nanoTime();
        long blackhole = 0;
        try (VectorSchemaRoot root = VectorSchemaRoot.create(batchSchema(q), alloc)) {
            for (int c = 0; c < cols; c++) {
                ((BigIntVector) root.getVector(c)).allocateNew(BATCH);
            }
            for (int start = 0; start < maxDoc; start += BATCH) {
                int len = Math.min(BATCH, maxDoc - start);
                for (int i = 0; i < len; i++) {
                    docs[i] = start + i;
                }
                for (int c = 0; c < cols; c++) {
                    BigIntVector vec = (BigIntVector) root.getVector(c);
                    long byteLen = (long) len * Long.BYTES;
                    MemorySegment dst = MemorySegment.ofAddress(vec.getDataBuffer().memoryAddress()).reinterpret(byteLen);
                    if (dvs[c].longValuesInto(len, docs, 0, dst, 0L, 0L) == false) {
                        dvs[c].longValues(len, docs, 0, fallbackScratch, 0, 0L);
                        dst.copyFrom(MemorySegment.ofArray(fallbackScratch).asSlice(0, byteLen));
                    }
                    blackhole += dst.get(java.lang.foreign.ValueLayout.JAVA_LONG, 0);
                }
            }
        }
        long elapsed = System.nanoTime() - t0;
        assertTrue(blackhole != Long.MIN_VALUE);
        return elapsed;
    }

    // ---------------------------------------------------------------
    // Substrait builders for path D (Calcite → substrait, reading input-0)
